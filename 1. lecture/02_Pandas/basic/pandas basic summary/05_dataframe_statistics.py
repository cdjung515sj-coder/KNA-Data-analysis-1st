# ============================================================
# Pandas DataFrame 통계 정리
# ============================================================
#
# 학습 순서
# 1. 개수 관련 통계
# 2. 중심값
# 3. 퍼짐 정도
# 4. 범위 / 분위수
# 5. 요약 통계 describe()
# 6. 결측치 통계
# 7. 실제 분석에서 자주 쓰는 흐름
# 8. 주의사항 / 헷갈리는 부분
#
# ============================================================

import pandas as pd
import numpy as np


# ------------------------------------------------------------
# 0. 예제 데이터
# ------------------------------------------------------------

df = pd.DataFrame({
    "설비": ["모터", "펌프", "밸브", "모터", "펌프"],
    "온도": [70, 85, 95, 82, np.nan],
    "압력": [100, 110, 95, 120, 105],
    "진동": [2.1, 4.8, 6.2, 5.5, 2.5],
    "상태": ["정상", "주의", "고장", "주의", "정상"]
})

print("===== 원본 데이터 =====")
print(df)


# ============================================================
# 1. 개수 관련 통계
# ============================================================

# count() : NaN을 제외한 값의 개수
print("\n===== df.count() =====")
print(df.count())
print("온도 count:", df["온도"].count())

# size : NaN을 포함한 전체 원소 개수
print("\n===== df.size =====")
print("DataFrame 전체 원소 수:", df.size)
print("온도 전체 칸 수:", df["온도"].size)

# value_counts() : 각 값이 몇 번 등장했는지
print("\n===== 상태별 개수 =====")
print(df["상태"].value_counts())


# ============================================================
# 2. 중심값
# ============================================================

# mean() : 평균
print("\n===== 평균 =====")
print("온도 평균:", df["온도"].mean())

# median() : 중앙값
print("\n===== 중앙값 =====")
print("온도 중앙값:", df["온도"].median())

# mode() : 최빈값
print("\n===== 최빈값 =====")
print(df["상태"].mode())


# ============================================================
# 3. 퍼짐 정도
# ============================================================

# std() : 표준편차
print("\n===== 표준편차 =====")
print("온도 표준편차:", df["온도"].std())

# var() : 분산
print("\n===== 분산 =====")
print("온도 분산:", df["온도"].var())


# ============================================================
# 4. 범위 / 분위수
# ============================================================

print("\n===== 최솟값 / 최댓값 =====")
print("온도 최소:", df["온도"].min())
print("온도 최대:", df["온도"].max())

print("\n===== 분위수 =====")
print("Q1:", df["온도"].quantile(0.25))
print("Q2:", df["온도"].quantile(0.50))
print("Q3:", df["온도"].quantile(0.75))

# IQR 계산
Q1 = df["온도"].quantile(0.25)
Q3 = df["온도"].quantile(0.75)
IQR = Q3 - Q1
lower = Q1 - 1.5 * IQR
upper = Q3 + 1.5 * IQR

print("\n===== IQR =====")
print("IQR:", IQR)
print("하한:", lower)
print("상한:", upper)


# ============================================================
# 5. describe()
# ============================================================

# 기본: 숫자형 컬럼 요약
print("\n===== describe() =====")
print(df.describe())

# 숫자형 전체
print("\n===== describe(include='number') =====")
print(df.describe(include="number"))

# 모든 자료형
print("\n===== describe(include='all') =====")
print(df.describe(include="all"))


# ============================================================
# 6. 결측치 통계
# ============================================================

# isna().sum() : 각 컬럼 NaN 개수
print("\n===== 결측치 개수 =====")
print(df.isna().sum())

# notna().sum() : 각 컬럼 실제 값 개수
print("\n===== 값이 있는 개수 =====")
print(df.notna().sum())


# ============================================================
# 7. 실제 분석에서 자주 쓰는 기본 흐름
# ============================================================
#
# df.head()                  -> 앞부분 확인
# df.info()                  -> 구조 / dtype / 결측치 확인
# df.isna().sum()            -> 결측치 개수 확인
# df.describe(include="number") -> 숫자형 요약
# df["상태"].value_counts() -> 범주형 값 분포 확인
#
# ============================================================


# ============================================================
# 8. 주의사항 / 많이 헷갈리는 부분
# ============================================================

# ------------------------------------------------------------
# 1) count() vs size
# ------------------------------------------------------------
# count() -> NaN 제외
# size    -> NaN 포함
#
# 예: [70, 80, NaN, 90]
# count() = 3
# size    = 4


# ------------------------------------------------------------
# 2) count() vs value_counts()
# ------------------------------------------------------------
# count()
# -> 값이 총 몇 개 있는지
#
# value_counts()
# -> 각각의 값이 몇 번 등장했는지
#
# 예: 정상, 정상, 고장, 주의
# count() = 4
# value_counts() = 정상 2 / 고장 1 / 주의 1


# ------------------------------------------------------------
# 3) mean() vs median()
# ------------------------------------------------------------
# mean()   -> 평균, 이상치 영향을 많이 받을 수 있음
# median() -> 중앙값, 이상치 영향을 덜 받음


# ------------------------------------------------------------
# 4) std() vs var()
# ------------------------------------------------------------
# std() -> 표준편차
# var() -> 분산
#
# 둘 다 퍼짐 정도를 나타낸다.
# 표준편차는 원래 데이터와 단위가 같아서 해석이 더 직관적이다.


# ------------------------------------------------------------
# 5) describe()는 이상치를 자동으로 찾아주지 않는다
# ------------------------------------------------------------
# describe()는 min, max, 25%, 50%, 75% 등을 보여준다.
# 이상치 여부는 IQR, Z-score, 3시그마 등의 기준으로 판단해야 한다.


# ------------------------------------------------------------
# 6) include="number" vs include="all"
# ------------------------------------------------------------
# include="number" -> int, float 등 숫자형 전체
# include="int"    -> 정수형
# include="float"  -> 실수형
# include="all"    -> 숫자 + 문자열 등 모든 자료형


# ------------------------------------------------------------
# 7) NaN은 대부분의 통계 계산에서 기본적으로 제외된다
# ------------------------------------------------------------
# mean(), median(), std(), var(), min(), max() 등은
# 기본적으로 NaN을 제외하고 계산한다.
#
# NaN 개수는:
# df.isna().sum()


# ------------------------------------------------------------
# 8) Series와 DataFrame의 결과 형태가 다를 수 있다
# ------------------------------------------------------------
# df["온도"].mean()
# -> 숫자 하나
#
# df[["온도", "압력"]].mean()
# -> 컬럼별 평균을 가진 Series


# ------------------------------------------------------------
# 9) 문자열 컬럼에는 숫자 통계를 바로 쓸 수 없다
# ------------------------------------------------------------
# 상태, 설비명처럼 문자열 데이터는 평균/표준편차 계산이 의미가 없다.
#
# 문자열/범주형 데이터에는 주로:
# value_counts()
# mode()
# describe(include="all")
# 등을 사용한다.


# ------------------------------------------------------------
# 10) 메서드 vs 속성
# ------------------------------------------------------------
# 메서드 -> () 필요
# df.count()
# df.mean()
# df.describe()
#
# 속성 -> () 없음
# df.size
# df.shape
# df.ndim
# df.dtypes


# ============================================================
# 9. 최종 요약
# ============================================================
#
# 개수
# count()        -> NaN 제외 값 개수
# size           -> NaN 포함 전체 원소 수
# value_counts() -> 값별 등장 횟수
#
# 중심
# mean()         -> 평균
# median()       -> 중앙값
# mode()         -> 최빈값
#
# 퍼짐
# std()          -> 표준편차
# var()          -> 분산
#
# 범위
# min()          -> 최솟값
# max()          -> 최댓값
# quantile()     -> 분위수
#
# 요약
# describe()     -> 숫자형 요약 통계
# describe(include="all") -> 전체 자료형 요약
#
# 결측치
# isna().sum()   -> NaN 개수
# notna().sum()  -> 값이 있는 개수
#
