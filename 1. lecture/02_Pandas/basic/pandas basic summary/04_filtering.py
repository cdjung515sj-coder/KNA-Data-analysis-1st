import pandas as pd

# 인덱스 새로 부여 0,1,2...	reset_index(drop=True)
# 인덱스 기준 오름차순	sort_index(ascending=True)
# 인덱스 기준 내림차순	sort_index(ascending=False)
# 컬럼 값 기준 오름차순	sort_values("컬럼")
