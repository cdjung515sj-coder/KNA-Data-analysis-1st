# ------------------------------------------------------------
# 0. 예제 데이터 만들기
# ------------------------------------------------------------

df = pd.DataFrame(
    {
        "설비": ["모터", "펌프", "밸브", "모터", "펌프", "밸브"],
        "온도": [70, 85, 95, 82, 60, 91],
        "진동": [2.1, 4.8, 6.2, 5.5, 2.5, 7.1],
        "압력": [100, 110, 95, 120, 105, 90],
        "상태": ["정상", "주의", "고장", "주의", "정상", "고장"],
    }
)

print("===== 원본 데이터 =====")
print(df)
print(f"print(df['압력'] < 110) -> 불리언(True/False)으로 출력됨 \n {df["압력"] < 110}")
# 0     True
# 1    False
# 2     True
# 3    False
# 4     True
# 5     True
# Name: 압력, dtype: bool

print(
    f"print(df[df['압력'] < 110]) -> 조건에 맞는 True 값만 DF로 출력됨 \n {df[df["압력"] < 110]}"
)
#     설비  온도   진동   압력  상태
# 0  모터  70  2.1  100  정상
# 2  밸브  95  6.2   95  고장
# 4  펌프  60  2.5  105  정상
# 5  밸브  91  7.1   90  고장

# 인덱스 새로 부여하기
result = df[df["압력"] < 110]
result = result.reset_index(drop=True)
print(f"df[df['압력'] < 110] -> 인덱스 새로 부여하기 \n {result}")
#     설비  온도   진동   압력  상태
# 0  모터  70  2.1  100  정상
# 1  밸브  95  6.2   95  고장
# 2  펌프  60  2.5  105  정상
# 3  밸브  91  7.1   90  고장
# 요로코롬 인덱스 새로 순서대로 적용 완 ㅎㅎ

# ============================================================
# 1. 불린 인덱싱 활용
# ============================================================
#
# 불린 인덱싱은 Pandas 필터링의 가장 기본적인 방법이다.
#
# 기본 구조:
#
# df[조건]
#
# 조건식의 결과는 True / False로 만들어지고
# True인 행만 선택된다.
# ------------------------------------------------------------


# 1-1. 숫자 조건 필터링
# 온도가 80 이상인 행만 선택

print("\n===== 온도 80 이상 =====")

result = df[df["온도"] >= 80]

print(result)


# ------------------------------------------------------------
# 활용 예시
#
# - 온도가 기준 이상인 설비 찾기
# - 진동이 기준보다 높은 설비 찾기
# - 압력이 정상 범위를 벗어난 데이터 찾기
# - 특정 점수 이상인 학생 찾기
# - 매출이 일정 금액 이상인 상품 찾기
# ------------------------------------------------------------


# 1-2. 문자 조건 필터링
# 상태가 "고장"인 행 선택

print("\n===== 상태가 고장 =====")

result = df[df["상태"] == "고장"]

print(result)


# 1-3. 여러 조건 AND
#
# & : 두 조건을 모두 만족
#
# 주의:
# 각 조건에 괄호를 반드시 붙이는 습관을 들이는 것이 좋다.

print("\n===== 온도 80 이상 AND 진동 5 이상 =====")

result = df[(df["온도"] >= 80) & (df["진동"] >= 5)]

print(result)


# 1-4. 여러 조건 OR
#
# | : 둘 중 하나라도 만족

print("\n===== 온도 90 이상 OR 진동 6 이상 =====")

result = df[(df["온도"] >= 90) | (df["진동"] >= 6)]

print(result)


# 1-5. 조건 반대로 만들기
#
# ~ : NOT
#
# 상태가 고장이 아닌 행

print("\n===== 고장이 아닌 데이터 =====")

result = df[~(df["상태"] == "고장")]

print(result)


# ============================================================
# 2. query() 활용
# ============================================================
#
# query()도 조건에 맞는 행을 선택하는 필터링 방법이다.
#
# 불린 인덱싱:
#
# df[(df["온도"] >= 80) & (df["진동"] >= 5)]
#
# query():
#
# df.query("온도 >= 80 and 진동 >= 5")
#
# ⭐조건이 길어질 때 query()가 더 읽기 쉬울 수 있다. ⭐
# ------------------------------------------------------------


print("\n===== query(): 온도 80 이상 =====")

result = df.query("온도 >= 80")

print(result)


print("\n===== query(): 온도 80 이상 AND 진동 5 이상 =====")

result = df.query("온도 >= 80 and 진동 >= 5")

print(result)


# ------------------------------------------------------------
# query()에서 문자열 값 비교
#
# 바깥쪽은 큰따옴표
# 내부 문자열은 작은따옴표를 사용하면 편하다.
# ------------------------------------------------------------

print("\n===== query(): 상태가 고장 =====")

result = df.query("상태 == '고장'")

print(result)


# ------------------------------------------------------------
# query()에서 외부 변수 사용
#
# 외부 Python 변수를 query 안에서 사용할 때는
# 변수 앞에 @를 붙인다.
# ------------------------------------------------------------

limit = 85

print("\n===== query(): 외부 변수 사용 =====")

result = df.query("온도 >= @limit")

print(result)


# ============================================================
# 3. isin() 활용
# ============================================================
#
# isin()은 여러 값 중 하나에 포함되는지 검사한다.
#
# 예:
#
# df["상태"].isin(["고장", "주의"])
#
# 결과:
#
# True / False
#
# 즉, isin()은 Boolean Series를 만들어주는 메서드이다.
# ------------------------------------------------------------


print("\n===== 상태가 고장 또는 주의 =====")

result = df[df["상태"].isin(["고장", "주의"])]

print(result)


# ------------------------------------------------------------
# isin()을 사용하는 이유
#
# 아래처럼 OR 조건을 여러 번 쓰는 것보다
#
# (df["상태"] == "고장") |
# (df["상태"] == "주의") |
# (df["상태"] == "점검")
#
# 아래처럼 쓰는 것이 더 간단하다.
#
# df["상태"].isin(["고장", "주의", "점검"])
# ------------------------------------------------------------


# 3-1. 특정 값 제외하기
#
# ~isin()
#
# 고장과 주의를 제외

print("\n===== 고장 / 주의 제외 =====")

result = df[~df["상태"].isin(["고장", "주의"])]

print(result)


# 3-2. isin() + 다른 조건

print("\n===== 상태가 고장/주의 AND 온도 80 이상 =====")

result = df[(df["상태"].isin(["고장", "주의"])) & (df["온도"] >= 80)]

print(result)


# ============================================================
# 4. 실제 데이터 분석에서 자주 쓰는 필터링 활용
# ============================================================


# ------------------------------------------------------------
# 활용 1. 이상값 / 위험 데이터 찾기
# ------------------------------------------------------------
#
# 예:
# 온도가 90 이상이거나 진동이 6 이상이면 위험하다고 가정

print("\n===== 위험 데이터 =====")

danger = df[(df["온도"] >= 90) | (df["진동"] >= 6)]

print(danger)


# ------------------------------------------------------------
# 활용 2. 정상 데이터만 남기기
# ------------------------------------------------------------

print("\n===== 정상 데이터만 선택 =====")

normal = df[df["상태"] == "정상"]

print(normal)


# ------------------------------------------------------------
# 활용 3. 특정 설비들만 분석
# ------------------------------------------------------------
#
# 모터와 펌프만 선택

print("\n===== 모터 / 펌프만 선택 =====")

machines = df[df["설비"].isin(["모터", "펌프"])]

print(machines)


# ------------------------------------------------------------
# 활용 4. 특정 범위 데이터 찾기
# ------------------------------------------------------------
#
# 온도 80 이상 90 이하
#
# 방법 1
# ------------------------------------------------------------

print("\n===== 온도 80 이상 90 이하 =====")

result = df[(df["온도"] >= 80) & (df["온도"] <= 90)]

print(result)


# ------------------------------------------------------------
# 같은 조건은 between()으로도 가능
#
# between(최솟값, 최댓값)
#
# 기본적으로 양 끝값을 포함한다.
# ------------------------------------------------------------

print("\n===== between(): 온도 80 ~ 90 =====")

result = df[df["온도"].between(80, 90)]

print(result)


# ------------------------------------------------------------
# 활용 5. 필터링 후 필요한 열만 선택
# ------------------------------------------------------------
#
# 위험한 데이터에서 설비, 온도, 진동만 확인

print("\n===== 필터링 후 필요한 컬럼 선택 =====")

result = df.loc[(df["온도"] >= 90) | (df["진동"] >= 6), ["설비", "온도", "진동"]]

print(result)


# ============================================================
# 5. 초보자가 가장 많이 헷갈리는 부분
# ============================================================


# ------------------------------------------------------------
# 헷갈림 1. and / or를 사용하면 안 되는 경우
# ------------------------------------------------------------
#
# 잘못된 예:
#
# df[(df["온도"] >= 80) and (df["진동"] >= 5)]
#
# Pandas Series에는 일반 Python의 and/or 대신
#
# &  : AND
# |  : OR
#
# 를 사용해야 한다.
#
# 올바른 코드:

result = df[(df["온도"] >= 80) & (df["진동"] >= 5)]


# ------------------------------------------------------------
# 헷갈림 2. 괄호를 빼먹는 경우
# ------------------------------------------------------------
#
# 위험한 작성:
#
# df[df["온도"] >= 80 & df["진동"] >= 5]
#
# 연산 우선순위 때문에 의도와 다르게 처리될 수 있다.
#
# 안전한 작성:
#
# df[
#     (df["온도"] >= 80) &
#     (df["진동"] >= 5)
# ]
#
# 조건마다 괄호를 붙이는 습관을 들이자.
# ------------------------------------------------------------


# ------------------------------------------------------------
# 헷갈림 3. = 과 ==의 차이
# ------------------------------------------------------------
#
# =  : 변수에 값을 저장
# == : 값이 같은지 비교
#
# 잘못된 예:
#
# df[df["상태"] = "고장"]
#
# 올바른 예:
#
# df[df["상태"] == "고장"]
# ------------------------------------------------------------


# ------------------------------------------------------------
# 헷갈림 4. isin()에 문자열 하나만 넣는 경우
# ------------------------------------------------------------
#
# 잘못된 예:
#
# df["상태"].isin("고장")
#
# isin()에는 보통 리스트처럼
# 여러 값을 담을 수 있는 자료형을 넣는다.
#
# 올바른 예:
#
# df["상태"].isin(["고장"])
#
# 여러 값:
#
# df["상태"].isin(["고장", "주의"])
# ------------------------------------------------------------


# ------------------------------------------------------------
# 헷갈림 5. isin()과 ==의 차이
# ------------------------------------------------------------
#
# 하나만 비교:
#
# df["상태"] == "고장"
#
# 여러 값 비교:
#
# df["상태"].isin(["고장", "주의"])
#
# 하나만 찾을 때는 ==가 더 단순하고,
# 여러 값을 찾을 때는 isin()이 편하다.
# ------------------------------------------------------------


# ------------------------------------------------------------
# 헷갈림 6. ~ 위치
# ------------------------------------------------------------
#
# 특정 값들을 제외할 때:
#
# ~df["상태"].isin(["고장", "주의"])
#
# 전체 코드:
#
# df[
#     ~df["상태"].isin(["고장", "주의"])
# ]
#
# ~는 True / False를 반대로 만든다.
# ------------------------------------------------------------


# ------------------------------------------------------------
# 헷갈림 7. query() 안에서 문자열 비교
# ------------------------------------------------------------
#
# 잘못된 예:
#
# df.query("상태 == 고장")
#
# 여기서 고장은 변수처럼 인식될 수 있다.
#
# 올바른 예:
#
# df.query("상태 == '고장'")
# ------------------------------------------------------------


# ------------------------------------------------------------
# 헷갈림 8. query()에서 Python 변수 사용
# ------------------------------------------------------------
#
# limit = 80
#
# 잘못된 예:
#
# df.query("온도 >= limit")
#
# 올바른 예:
#
# df.query("온도 >= @limit")
#
# 외부 Python 변수에는 @를 붙인다.
# ------------------------------------------------------------


# ------------------------------------------------------------
# 헷갈림 9. 필터링은 원본 df를 자동으로 바꾸지 않는다
# ------------------------------------------------------------
#
# 아래 코드는 결과를 보여줄 뿐,
# 원본 df 자체를 변경하지 않는다.
#
# df[df["온도"] >= 80]
#
# 결과를 저장하려면:
#
# filtered_df = df[df["온도"] >= 80]
# ------------------------------------------------------------


# ------------------------------------------------------------
# 헷갈림 10. 문자열과 숫자를 구분해야 한다
# ------------------------------------------------------------
#
# 숫자:
#
# df[df["온도"] >= 80]
#
# 문자열:
#
# df[df["상태"] == "고장"]
#
# 만약 숫자 데이터가 문자열 형태라면:
#
# "80", "90", "100"
#
# 숫자 비교가 제대로 되지 않을 수 있다.
#
# 확인:
#
# print(df.dtypes)
#
# 필요하다면:
#
# df["온도"] = pd.to_numeric(df["온도"])
# ------------------------------------------------------------


# ============================================================
# 6. 실무에서 자주 사용하는 필터링 패턴
# ============================================================


# 패턴 1
# 기준 이상

result = df[df["온도"] >= 80]


# 패턴 2
# 특정 값

result = df[df["상태"] == "고장"]


# 패턴 3
# 두 조건 모두 만족

result = df[(df["온도"] >= 80) & (df["진동"] >= 5)]


# 패턴 4
# 둘 중 하나 만족

result = df[(df["온도"] >= 90) | (df["진동"] >= 6)]


# 패턴 5
# 여러 범주 중 하나

result = df[df["상태"].isin(["고장", "주의"])]


# 패턴 6
# 특정 범주 제외

result = df[~df["상태"].isin(["고장", "주의"])]


# 패턴 7
# 범위 조건

result = df[df["온도"].between(80, 90)]


# 패턴 8
# query() 사용

result = df.query("온도 >= 80 and 진동 >= 5")


# ============================================================
# 7. 최종 핵심 정리
# ============================================================
#
# 1) 불린 인덱싱
#
# df[조건]
#
# 조건의 결과가 True인 행만 선택한다.
#
#
# 2) 여러 조건
#
# AND  -> &
# OR   -> |
# NOT  -> ~
#
# 조건마다 괄호를 붙이는 습관이 중요하다.
#
#
# 3) query()
#
# df.query("조건")
#
# 조건이 길어질 때 읽기 편하다.
#
#
# 4) isin()
#
# 여러 값 중 하나인지 확인한다.
#
# df["상태"].isin(["고장", "주의"])
#
#
# 5) 가장 많이 하는 실수
#
# and / or 사용
# 괄호 누락
# = 와 == 혼동
# isin()에 리스트를 안 넣음
# query() 문자열 비교 따옴표 누락
# query() 외부 변수에 @ 누락
# 숫자/문자 자료형 혼동
#
#
# ------------------------------------------------------------
# 추천 학습 순서
# ------------------------------------------------------------
#
# 불린 인덱싱
#     ↓
# Boolean Series
#     ↓
# 비교 연산자
#     ↓
# &, |, ~
#     ↓
# query()
#     ↓
# isin()
#     ↓
# between()
#     ↓
# loc와 조합
#
# ============================================================
