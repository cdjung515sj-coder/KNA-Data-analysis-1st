"""
Pandas between() 정리

핵심:
- between(a, b) = a 이상 b 이하인지 검사
- 결과는 True/False로 이루어진 Boolean Series
- 실제 행을 가져오려면 df[조건] 형태로 사용
"""

import pandas as pd


# --------------------------------------------------
# 1. 예제 데이터 만들기
# --------------------------------------------------
df = pd.DataFrame({
    "온도": [65, 70, 75, 85, 90, 95, 105],
    "압력": [90, 100, 120, 150, 160, 180, 200]
})

print("=== 원본 데이터 ===")
print(df)


# --------------------------------------------------
# 2. between() 기본 사용
# --------------------------------------------------
# 온도가 70 이상 90 이하인지 확인
condition = df["온도"].between(70, 90)

print("\n=== 온도 70~90 사이인지 확인 ===")
print(condition)

# between(70, 90)은 아래 조건과 같은 의미
same_condition = (df["온도"] >= 70) & (df["온도"] <= 90)

print("\n=== 일반 비교 연산으로 작성 ===")
print(same_condition)


# --------------------------------------------------
# 3. 실제 행 필터링
# --------------------------------------------------
result = df[df["온도"].between(70, 90)]

print("\n=== 온도 70 이상 90 이하인 행 ===")
print(result)


# --------------------------------------------------
# 4. inclusive 옵션
# --------------------------------------------------
# 기본값: inclusive="both"
# 70 <= x <= 90
both = df["온도"].between(70, 90, inclusive="both")

# 70 < x < 90
neither = df["온도"].between(70, 90, inclusive="neither")

# 70 <= x < 90
left = df["온도"].between(70, 90, inclusive="left")

# 70 < x <= 90
right = df["온도"].between(70, 90, inclusive="right")

print("\n=== inclusive='both' : 70 <= x <= 90 ===")
print(df[both])

print("\n=== inclusive='neither' : 70 < x < 90 ===")
print(df[neither])

print("\n=== inclusive='left' : 70 <= x < 90 ===")
print(df[left])

print("\n=== inclusive='right' : 70 < x <= 90 ===")
print(df[right])


# --------------------------------------------------
# 5. ~ 를 사용해서 범위 밖의 값 찾기
# --------------------------------------------------
# ~ 는 조건을 반대로 만든다.
# 즉, 70~90 범위가 아닌 값 찾기
outside = df[~df["온도"].between(70, 90)]

print("\n=== 온도 70~90 범위를 벗어난 행 ===")
print(outside)


# --------------------------------------------------
# 6. 여러 조건과 함께 사용
# --------------------------------------------------
# 온도: 70~90
# 압력: 100~160
multi_condition = (
    df["온도"].between(70, 90)
    & df["압력"].between(100, 160)
)

print("\n=== 온도 70~90 AND 압력 100~160 ===")
print(df[multi_condition])


# --------------------------------------------------
# 7. 자주 헷갈리는 부분
# --------------------------------------------------

# [주의 1]
# between() 자체의 결과는 실제 데이터가 아니라 True/False이다.
#
# df["온도"].between(70, 90)
# -> Boolean Series
#
# 실제 행을 가져오려면:
# df[df["온도"].between(70, 90)]


# [주의 2]
# Pandas Series 조건에서는 and가 아니라 & 사용
#
# 잘못된 예:
# df["온도"] >= 70 and df["온도"] <= 90
#
# 올바른 예:
# (df["온도"] >= 70) & (df["온도"] <= 90)
#
# 또는 더 간단하게:
# df["온도"].between(70, 90)


# [주의 3]
# between(작은 값, 큰 값) 순서로 작성
#
# 권장:
# df["온도"].between(70, 90)


# [주의 4]
# .isin()과 헷갈리지 않기
#
# between()
# -> 범위 검사
# 예: 70~90 사이인가?
#
# isin()
# -> 특정 값 목록에 포함되는지 검사
# 예: 상태가 "정상", "주의" 중 하나인가?
#
# 예:
# df["상태"].isin(["정상", "주의"])


# --------------------------------------------------
# 8. 핵심 암기
# --------------------------------------------------
print("\n=== 핵심 암기 ===")
print('df["온도"].between(70, 90)')
print("= 70 <= 온도 <= 90")
print("= True / False 반환")
print('실제 행 선택: df[df["온도"].between(70, 90)]')
