# 산술 연산자 ( + - * / | // (몫) % (나머지) ** (거듭제곱)
print(3 + 5)  # 8
print(10 - 4)  # 6
print(4 * 5)  # 20
print(20 / 4)  # 5.0 ( 나눗셈 결과는 항상 float(실수))

print(7 // 3)  # 2 ( 나눗셈 결과의 몫 )
print(7 % 3)  # 1 ( 7개의 음료수를 3 봉투에 나누면, 2개의 봉투와 1개의 음료수가 남음 )
print(2**5)  # 32 ( 2 의 5 제곱 )

# =========================================================================

# 연산 우선순위과 우선순위 지정
# ** (거듭제곱) > * (곱하기) = / (나누기) = // (몫) = % (나머지) > +(더하기) = - (빼기)

print(2 + 8 * 3)  # 8*3 연산 후 그 결과를 2와 더함
print((2 + 8) * 3)  # 괄호 안의 연산을 먼저 한 뒤 곱하기 계산

