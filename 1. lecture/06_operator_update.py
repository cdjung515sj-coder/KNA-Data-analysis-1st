# =========================================================================
print("=========== 비교 연산자 ============")

# < (미만), > (초과), <= (이하), >= (이상), == (같다), != (다르다)
# 비교 결과는 무조건 True or False (종류는 "bool" )

print(7 < 16)  # True
print(7 > 16)  # False
print(7 <= 16)  # True
print(7 >= 16)  # False
print(7 != 16)  # True
print(7 == 7)  # True
print(7 == 16)  # False

# 비교 연산자는 문자열 비교도 가능
print("Hello" == "Hello")  # True
print("정상" == "정상")

# 비교 연산자를 사용해 문자열을 비교할 때 주의사항

## 1. 대소문자 구문
print("Hello" == "hello")  # False

## 2. 공백이 있어도 다르다고 판단
print("정상" == "정상 ")  # False

## 부정연산자 != (not 의미)
print("Hello" != "Hello")  # False ( 두 값이 동일한데 !로 인해서 값이 반대로 출력됨)
print("Hello" != "hello")  # True
print("hello" != "hello ")  # True ( 공백이 없고/있고 다르기 때문)

