# + : 더하기
# - : 빼기
# * : 곱하기
# / : 나누기
# // : 몫
# % : 나머지

print(7 + 14)  # 21
print(7 - 14)  # -7 (계산 결과가 음수여도 출력 가능하다)
print(7 * 14)  # 98
print(7 / 14)  # 0.5 (나누기 결과는 소수점까지 출력 가능하다)

print(75 + 80 / 2)  # 115.0 (나누기 먼저 계산)
print((75 + 80) / 2)  # 77.5 (괄호 안의 계산 먼저 수행)

