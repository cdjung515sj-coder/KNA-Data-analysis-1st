# 실습 - 합/차/평균 계산

print("두 측정값의 합:", 7 + 77.5)
print("온도 변화량:", 77.5 - 7)
print("평균 온도:", (75 + 77.5) / 2)

Temperature_1st = 75
Temperature_2nd = 80

print("두", "측정값의", "합" + ":", Temperature_1st + Temperature_2nd)
print("온도", "변화량" + ":", abs(Temperature_1st - Temperature_2nd))
print("평균", "온도" + ":", (Temperature_1st + Temperature_2nd) / 2)


