import numpy as np
import pandas as pd

# ============================================
# 1. DataFrame 개념
# ============================================

# DataFrame
# - Pandas의 2차원 자료구조
# - ✅ 행(row)과 열(column)로 구성됨
# - 표 형태의 데이터를 다룰 때 사용
# - 여러 개의 Series가 모여 있는 구조라고 볼 수 있음

#           열(columns)
#        설비   온도   압력
# 행 0    A     70    10
# 행 1    B     80    15
# 행 2    C     90    20
#  ↑
# index

# ⭐⭐ 행(row) # 열(column) # index  # 데이터 값(value)으로 이뤄진 2차원 자료구조 ⭐⭐


df = pd.DataFrame({"설비": ["A", "B", "C"], "온도": [70, 80, 90], "압력": [10, 15, 20]})

print("기본 DataFrame")
print(df)

# 구조
#
#       설비   온도   압력   <- columns
# 0      A    70    10
# 1      B    80    15
# 2      C    90    20
# ^
# index


# ============================================
# 2. DataFrame 만들기
# ============================================

# 가장 많이 사용하는 방법:
# 딕셔너리를 pd.DataFrame()에 넣기

data = {"설비": ["A", "B", "C"], "온도": [70, 80, 90], "압력": [10, 15, 20]}

df1 = pd.DataFrame(data)

print("\n딕셔너리로 DataFrame 만들기")
print(df1)


# index를 직접 지정할 수도 있음

df2 = pd.DataFrame(
    {"온도": [70, 80, 90], "압력": [10, 15, 20]}, index=["모터", "펌프", "밸브"]
)

print("\nindex를 지정한 DataFrame")
print(df2)

# 열 이름을 Key라고 하고, 리스트를 value로 갖는 딕셔너리 2차원 데이터 생성
dict_data = {
    "c0": [1, 2, 3],
    "c1": [4, 5, 6],
    "c2": [7, 8, 9],
    "c3": [10, 11, 12],
    "c4": [13, 14, 15],
}

# 판다스 DataFrame() 함수로 딕셔너리 -> DataFrame 로 형 변환
df_dict = pd.DataFrame(dict_data)

print(f"딕셔너리를 데이터프레임으로 형변환 \n {df_dict}")
#     c0  c1  c2  c3  c4
# 0   1   4   7  10  13
# 1   2   5   8  11  14
# 2   3   6   9  12  15

# ============================================
# 3. DataFrame의 index / columns 구조
# ============================================

# DataFrame은 크게
# index + columns + values 구조로 볼 수 있음

# columns
# -> 열 이름

# index
# -> 행 이름

# values
# -> 실제 데이터 값


df = pd.DataFrame(
    {"온도": [78, 82, 91], "압력": [12, 15, 18]}, index=["모터", "펌프", "밸브"]
)

print("\nindex / columns 구조")
print(df)

#             columns
#          온도     압력
# index
# 모터      78      12
# 펌프      82      15
# 밸브      91      18


# index를 지정하지 않으면
# 0, 1, 2, ... 형태의 기본 index가 자동 생성됨


# ============================================
# 4. DataFrame 속성
# ============================================

df = pd.DataFrame(
    {"설비": ["A", "B", "C", "D"], "온도": [65, 78, 85, 92], "압력": [10, 15, 18, 21]}
)

print("\nDataFrame 속성")

print("index:", df.index)  # 행 index
print("columns:", df.columns)  # 열 이름
print("values:")
print(df.values)  # 실제 값
print("shape:", df.shape)  # (행 개수, 열 개수)
print("size:", df.size)  # 전체 원소 개수
print("ndim:", df.ndim)  # 차원 수
print("dtypes:")
print(df.dtypes)  # 각 열의 자료형

# 중요
# DataFrame은 2차원이므로
# df.ndim -> 2

# shape
# -> (행 개수, 열 개수)

# size
# -> 행 개수 × 열 개수

# 속성은 ()를 붙이지 않음
#
# df.shape     # O
# df.shape()   # X


# ============================================
# 5. 행 / 열 / 원소 선택
# ============================================

df = pd.DataFrame(
    {"설비": ["A", "B", "C", "D"], "온도": [65, 78, 85, 92], "압력": [10, 15, 18, 21]}
)


# --------------------------------------------
# 5-1. 열 하나 선택
# --------------------------------------------

print("\n열 하나 선택")
print(df["온도"])

# 열 하나 선택
# -> 결과는 Series

# df["온도"]
# -> Series


# --------------------------------------------
# 5-2. 여러 열 선택
# --------------------------------------------

print("\n여러 열 선택")
print(df[["온도", "압력"]])

# 여러 열 선택
# -> 결과는 DataFrame

# df[["온도", "압력"]]
# -> DataFrame


# --------------------------------------------
# 5-3. loc
# --------------------------------------------

# loc
# -> index 이름과 column 이름으로 선택

print("\nloc으로 선택")
print(df.loc[0, "온도"])

# 0번 index의 온도 값 선택


print("\nloc으로 행과 열 선택")
print(df.loc[0:2, ["설비", "온도"]])

# loc 슬라이싱은 마지막 값도 포함함
# 0:2 -> 0, 1, 2


# --------------------------------------------
# 5-4. iloc
# --------------------------------------------

# iloc
# -> 위치 번호로 선택

print("\niloc으로 선택")
print(df.iloc[0, 1])

# 0번째 행, 1번째 열


print("\niloc으로 범위 선택")
print(df.iloc[0:3, 0:2])

# iloc 슬라이싱은 끝 번호를 포함하지 않음
# 0:3 -> 0, 1, 2


# 핵심
#
# loc
# -> 이름 / 조건 중심
#
# iloc
# -> 위치 번호 중심


# ============================================
# 6. DataFrame 객체를 만드는 특수한 방법
# ============================================


# --------------------------------------------
# 6-1. 딕셔너리로 만들기
# --------------------------------------------

data_dict = {"설비": ["A", "B", "C"], "온도": [70, 80, 90]}

df_dict = pd.DataFrame(data_dict)

print("\n딕셔너리로 만들기")
print(df_dict)

# dictionary key
# -> column 이름

# dictionary value
# -> 해당 column의 데이터


# --------------------------------------------
# 6-2. 리스트 안에 리스트로 만들기
# --------------------------------------------

data_list = [["A", 70, 10], ["B", 80, 15], ["C", 90, 20]]

df_list = pd.DataFrame(data_list, columns=["설비", "온도", "압력"])

print("\n2차원 리스트로 만들기")
print(df_list)


# --------------------------------------------
# 6-3. NumPy 배열로 만들기
# --------------------------------------------

arr = np.array([[70, 10], [80, 15], [90, 20]])

df_numpy = pd.DataFrame(arr, columns=["온도", "압력"])

print("\nNumPy 배열로 만들기")
print(df_numpy)


# --------------------------------------------
# 6-4. Series를 이용해 만들기
# --------------------------------------------

temp = pd.Series([70, 80, 90])
pressure = pd.Series([10, 15, 20])

df_series = pd.DataFrame({"온도": temp, "압력": pressure})

print("\nSeries를 이용해 만들기")
print(df_series)

# 여러 Series가 모이면
# DataFrame 형태로 만들 수 있음


# ============================================
# 7. DataFrame 활용
# ============================================

df = pd.DataFrame(
    {
        "설비": ["A", "B", "C", "D", "E"],
        "온도": [65, 72, 85, 91, 78],
        "압력": [10, 15, 13, 20, 17],
        "품질": ["정상", "정상", "주의", "불량", "정상"],
    }
)


# --------------------------------------------
# 7-1. 데이터 확인
# --------------------------------------------

print("\n처음 5행")
print(df.head())

print("\n마지막 5행")
print(df.tail())

print("\nDataFrame 크기")
print(df.shape)


# --------------------------------------------
# 7-2. 조건 만들기
# --------------------------------------------

condition = df["온도"] >= 80

print("\n온도 80 이상 조건")
print(condition)

# df["온도"]
# -> Series

# df["온도"] >= 80
# -> Boolean Series


# --------------------------------------------
# 7-3. Boolean Indexing
# --------------------------------------------

result = df[df["온도"] >= 80]

print("\n온도 80 이상 데이터")
print(result)


# --------------------------------------------
# 7-4. 여러 조건으로 필터링
# --------------------------------------------

result2 = df[(df["온도"] >= 80) & (df["압력"] >= 15)]

print("\n온도 80 이상 AND 압력 15 이상")
print(result2)

# Pandas 다중 조건
#
# &  -> AND
# |  -> OR
# ~  -> NOT
#
# 각 조건은 괄호로 묶는 것이 중요


# --------------------------------------------
# 7-5. 원하는 열까지 함께 선택
# --------------------------------------------

result3 = df.loc[df["온도"] >= 80, ["설비", "온도"]]

print("\n조건 + 원하는 열 선택")
print(result3)


# --------------------------------------------
# 7-6. 정렬
# --------------------------------------------

sorted_df = df.sort_values("온도", ascending=False)

print("\n온도 내림차순 정렬")
print(sorted_df)


