"""
[ 분석 5단계 flow ]

# 1. 불러오기
df = pd.read_csv("파일.csv")


# 2. 확인
df.head()
df.info()
df.shape
df.columns
df.describe()


# 3. 필터링
df[df["열"] >= 값]

df[(조건1) & (조건2)]       # AND
df[(조건1) | (조건2)]       # OR

df[df["열"].isin([...])]    # 여러 값
df[df["열"].between(a, b)]  # 범위
df[~조건]                   # 부정


# 4. 정렬
df.sort_values("열")                     # 오름차순
df.sort_values("열", ascending=False)    # 내림차순


# 5. 선택
df["열"]                    # 한 열 → Series
df[["열1", "열2"]]          # 여러 열 → DataFrame

df.loc[행, 열]              # 이름/조건 기준
df.iloc[행번호, 열번호]      # 위치 기준

"""

# ============================================================
# Python copy 총정리
# ============================================================

# 핵심:
# 원본 데이터를 유지하면서 "복사본"을 수정하고 싶을 때 copy를 사용한다.
#
# 꼭 구분하기!
# 1. b = a                 → 복사 X, 같은 객체를 바라봄
# 2. b = a.copy()          → 얕은 복사
# 3. copy.deepcopy(a)      → 깊은 복사

# 원본인지 복사본인지 모호할 때 뜨는 경고로 이름은 길지만 뜻은 단순함 
# 결과를 장담 못한다는 뜻
# 오류가 아닌 경고이므로 copy나 loc으로 해결할 것
# | 빨간 글씨로 길게 나와 당황하기 쉽지만 코드는 멈추지 않고 끝까지 실행함
# SettingWithCopyWarning: A value is trying to be set on a copy of a slice from a DataFrame

# 따로 수정 .copy()
# 원본 수정 .loc
# 웬만하면 .copy() 사용할 것

# ============================================================
# 1. 대입 (=) : 복사가 아니다 ⭐⭐⭐
# ============================================================

a = [10, 20, 30]
b = a

# a와 b는 같은 리스트를 바라본다.
# 따라서 b를 수정하면 a에서도 변경된 값이 보인다.

b[0] = 999

print(a)  # [999, 20, 30]
print(b)  # [999, 20, 30]

# 그림으로 이해
#
# a ──┐
#     ├──> [999, 20, 30]
# b ──┘
#
# 주의!
# b = a 를 "a를 b에 복사했다"라고 생각하면 안 된다.
# 같은 객체에 이름을 하나 더 붙였다고 생각하면 쉽다.


# ============================================================
# 2. .copy() : 얕은 복사 (Shallow Copy) ⭐⭐⭐
# ============================================================

a = [10, 20, 30]
b = a.copy()

# 새로운 리스트가 만들어진다.
# 따라서 b를 수정해도 a는 변경되지 않는다.

b[0] = 999

print(a)  # [10, 20, 30]
print(b)  # [999, 20, 30]


# 값이 같은지 확인
a = [10, 20, 30]
b = a.copy()

print(a == b)  # True  → 들어있는 값은 같음
print(a is b)  # False → 서로 다른 객체임


# ============================================================
# 3. 얕은 복사의 주의점 ⚠️
# ============================================================

# 리스트 안에 리스트가 있는 "중첩 리스트"에서는 주의해야 한다.

a = [[10, 20], [30, 40]]
b = a.copy()

# 바깥 리스트는 새로 만들어졌지만
# 안쪽 리스트는 서로 공유하고 있다.

b[0][0] = 999

print(a)  # [[999, 20], [30, 40]]
print(b)  # [[999, 20], [30, 40]]

# 즉,
# .copy()를 했다고 해서
# 내부에 들어있는 객체까지 전부 새로 만들어지는 것은 아니다.
#
# 이것을 "얕은 복사"라고 한다.


# ============================================================
# 4. deepcopy() : 깊은 복사
# ============================================================

import copy

a = [[10, 20], [30, 40]]

b = copy.deepcopy(a)

# 내부 리스트까지 새롭게 복사한다.

b[0][0] = 999

print(a)  # [[10, 20], [30, 40]]
print(b)  # [[999, 20], [30, 40]]

# 원본과 복사본을 완전히 독립적으로 만들고 싶다면
# deepcopy()를 사용한다.


# ============================================================
# 5. 리스트를 얕게 복사하는 여러 방법
# ============================================================

a = [10, 20, 30]

b = a.copy()   # 방법 1 ⭐ 가장 직관적
c = a[:]       # 방법 2 : 슬라이싱
d = list(a)    # 방법 3 : 새로운 리스트 생성

# 위 방법들은 모두 리스트의 "얕은 복사"이다.


# ============================================================
# 6. copy.copy()도 있다
# ============================================================

import copy

a = [10, 20, 30]

b = copy.copy(a)      # 얕은 복사
c = copy.deepcopy(a)  # 깊은 복사

# 헷갈리지 않기!
#
# a.copy()          → 얕은 복사
# copy.copy(a)      → 얕은 복사
# copy.deepcopy(a)  → 깊은 복사


# ============================================================
# 7. 언제 사용하나?
# ============================================================

# 예:
# 원본 센서 데이터는 보존하면서
# 테스트용 데이터만 변경하고 싶은 경우

sensor = [70, 75, 80, 85]

test_sensor = sensor.copy()

test_sensor[0] = 999

print("원본:", sensor)
# [70, 75, 80, 85]

print("테스트:", test_sensor)
# [999, 75, 80, 85]


