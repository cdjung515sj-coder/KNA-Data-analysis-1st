# 추가 질문
# - 왜 리드타임이 길어지면 같은 고장도
#   예측 가능형에서 간격 부족형으로 바뀔 수 있을까요?


# ------------------------------------------------------------
# Step 4. 예측 가능형의 목표 조기 경보 시점 계산
# ------------------------------------------------------------

# [문제]
# 케이스 A에서 "예측 가능형"으로 판정된 사례만 선택하세요.


# 목표 경보 시점은 다음과 같이 정합니다.
#
#   목표 경보 시점 = P-F 간격의 50%
#
# 계산한 값은 반올림한 뒤 정수로 변환하고,
# 새로운 컬럼 이름은 "목표경보_일전"으로 만드세요.
#
# 출력할 컬럼
# - 사례ID
# - 설비
# - PF간격_일
# - 목표경보_일전

예측가능 = df[df["케이스A_판정"] == "예측 가능형"].copy()

예측가능["목표경보_일전"] = (예측가능["PF간격_일"] * 0.5).round().astype(int)

print(예측가능[["사례ID", "설비", "PF간격_일", "목표경보_일전"]])


# ------------------------------------------------------------
# Step 5. 예측 불가 사례의 대응 방향 정하기
# ------------------------------------------------------------

# [문제]
# 케이스 B에서 "예측 가능형"이 아닌 사례만 선택하세요.

예측불가 = df[df["케이스B_판정"] != "예측 가능형"].copy()

# 아래 기준에 따라 대응 방향을 연결하세요.
#
# 물리적 돌발
#   → 이중화 또는 정기 교체
#
# 간격 부족형
#   → 보호 로직 또는 자동 정지
#
# 측정 부재형
#   → 계측 개선 또는 저장 주기 조정

대응 = {
    "물리적 돌발": "이중화 또는 정기 교체",
    "간격 부족형": "보호 로직 또는 자동 정지",
    "측정 부재형": "계측 개선 또는 저장 주기 조정",
}

# 새로운 컬럼 이름은 "대응방향"으로 만드세요.

예측불가["대응방향"] = 예측불가["케이스B_판정"].map(대응)

# 출력할 컬럼
# - 사례ID
# - 설비
# - 케이스B_판정
# - 대응방향

print(예측불가[["사례ID", "설비", "케이스B_판정", "대응방향"]])

