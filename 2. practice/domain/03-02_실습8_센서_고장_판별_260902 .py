import pandas as pd

df = pd.read_csv("data/03-02_센서_고장_판별_이상구간샘플_260902_Question_2.csv")

alarm = pd.read_csv("data/03-02_센서_고장_판별_정비알람이력_260902_Question_3.csv")

df["timestamp"] = pd.to_datetime(df["timestamp"])
alarm["event_time"] = pd.to_datetime(alarm["event_time"])


# 1. HYD02_PRESS 같은 값 연속 횟수
press_group = (df["HYD02_PRESS"] != df["HYD02_PRESS"].shift()).cumsum()

press_result = df.groupby(press_group).agg(
    value=("HYD02_PRESS", "first"),
    count=("HYD02_PRESS", "size"),
    start=("timestamp", "first"),
    end=("timestamp", "last"),
    run_min=("MTR02_RUN", "min"),
    run_max=("MTR02_RUN", "max"),
)

press_running = press_result[
    (press_result["run_min"] == 1) & (press_result["run_max"] == 1)
]

print(press_running.sort_values("count", ascending=False).head(1))


# 2. HYD02_PRESS_ACC 최대값 확인
acc_max = df["HYD02_PRESS_ACC"].max()

acc_check = df[df["HYD02_PRESS_ACC"] == acc_max]

print("\nHYD02_PRESS_ACC 최대값:", acc_max)
print("최대값 개수:", len(acc_check))


# 3. HYD02_FLOW 흔들림 비교
running = df[df["MTR02_RUN"] == 1].copy()

running["date"] = running["timestamp"].dt.date

flow_std = running.groupby("date")["HYD02_FLOW"].std().round(3)

print("\nHYD02_FLOW 표준편차")
print(flow_std)


# 4. FUR02_TEMP_Z1 급격한 값 확인
spike = df[df["FUR02_TEMP_Z1"] >= 1300][["timestamp", "FUR02_TEMP_Z1"]]

print("\nFUR02_TEMP_Z1 이상값")
print(spike)


# 5. 관련 정비/알람
tags = ["HYD02_PRESS", "HYD02_PRESS_ACC", "HYD02_FLOW", "FUR02_TEMP_Z1"]

print(alarm[alarm["tag"].isin(tags)])

