# 실습 4. agg 진단표 만들기
# 목표
# 여러 통계를 담은 진단표를 만들고 정렬해 우선순위 파악
import pandas as pd

df_hydraulic = pd.read_csv("data/14_hydraulic.csv", encoding="utf-8")

# 단계
# · 설비로 그룹을 나눠 측정수·평균온도·온도편차·평균진동·평균압력을 이름 붙여 집계
report = (
    df_hydraulic.groupby("밸브상태")
    .agg(
        측정수=("온도", "count"),
        평균온도=("온도", "mean"),
        온도편차=("온도", "std"),
        평균진동=("진동", "mean"),
        평균압력=("압력", "mean"),
    )
    .round(3)
)

print(report)
#       측정수    평균온도   온도편차   평균진동     평균압력
# 밸브상태                                    
# 경미     20  44.860  8.110  0.617  161.562
# 심각     19  46.021  8.395  0.629  163.391
# 정상     61  45.113  7.790  0.609  159.987
# 지연     20  45.860  8.928  0.621  161.266


# · 온도편차를 기준으로 내림차순 정렬

print(report.sort_values("온도편차", ascending=False))
#       측정수    평균온도   온도편차   평균진동     평균압력
