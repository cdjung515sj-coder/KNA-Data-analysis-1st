import pandas as pd

df_sample = pd.read_csv("data/12_metro_digital.csv")

print("=== info() 데이터 건강검진 ===")
df_sample.info()

# 결측치 개수 직접 확인 (전체 행 수 - Non-Null Count)
print("=== 열별 결측치(NaN) 개수 ===")
print(df_sample.isnull().sum())


# 1. 결측이 있는 열을 세 개 이상 찾았는가
# - 결측이 있는 열이 단 하나도 없음 
# - 이유: 전체 120개 행 중 120 non-null로 채워져 있어 빈 값(NaN)이 존재하지 않습니다.

# 2. 가장 결측 많은 열의 개수를 계산했는가
# - 계산식: 전체 행 수(120) - Non-Null Count(120) = 0개
# - 가장 결측이 많은 열의 결측치 수는 '0개'입니다.

