# 실습 6. 처리 전후 통계 비교
# 목표
# 제거·보정·중앙값 채움 세 처리의 평균 변화 비교
# - 실린더압력 열에 대해 원본 상태, 행 제거 상태, clip 보정 상태, 그리고 중앙값 채움 상채의 펴육ㄴ 변화를 대조해보자
import pandas as pd

df = pd.read_csv("data/16_diecasting.csv", encoding="utf-8")
df.info()

# 단계
# · 실린더압력 이상치 경계와 조건을 만들기
q1 = df["실린더압력"].quantile(0.25)
q3 = df["실린더압력"].quantile(0.75)

IQR = q3 - q1
L = q1 - 1.5 * IQR
U = q3 + 1.5 * IQR

M = (df["실린더압력"] < L) | (df["실린더압력"] > U)
filled = df["실린더압력"].mask(M).fillna(df["실린더압력"].mask(M).median())


# · 제거·보정·중앙값 채움 세 방식을 각각 적용
# · 처리 전 평균과 세 방식의 평균을 나란히 비교
print(f"처리 전 {df['실린더압력'].mean():.2f}")
print(f"제거 {df[~M]['실린더압력'].mean():.2f}")
print(f"보정 {df['실린더압력'].clip(L,U).mean():.2f}")
print(f"채움 {filled.mean():.2f}")

# 예상 결과
