# 실습 1. 상관계수와 상관 행렬 구하기

import pandas as pd

# 목표
# 두 측정값의 상관계수를 구하고 여러 열의 상관 행렬 읽기
df_hydraulic_qc = pd.read_csv("data/14_hydraulic_qc.csv", encoding="utf-8")
df_hydraulic_qc.info()

# 단계
# · corr로 두 지표의 상관계수를 구해 부호와 절댓값 해석
# · 여러 지표 열을 골라 corr로 상관 행렬 생성

print(
    df_hydraulic_qc[["지표01", "지표02", "지표03", "지표04", "지표05"]].corr().round(3)
)

