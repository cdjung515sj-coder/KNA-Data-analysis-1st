# 조건으로 값을 골라낸 뒤 그 값들의 통계 계산

# 토크 배열 준비
torque8 = np.array([43.4, 43.6, 38.5, 47.5, 49.2, 60.4, 66.8, 29.3])

# 불리언 인덱싱으로 기준을 넘는 값만 추출
high8 = torque8[torque8 > 50]
print(high8)  # [60.4 66.8]

# 추출한 값들의 평균과 개수 계산
print(round(high8.mean(), 1))  # 63.6
print(high8.size)  # 2

